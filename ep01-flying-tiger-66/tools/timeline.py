"""Build build/vo/timeline.json from the edge-tts lines (build/vo/<key>.mp3 + <key>.json word timings).

Voice lines are generated by tools/tts.py (ms-MY-OsmanNeural) from tools/tts_lines.txt.
Subtitle chunks map display text (script spelling, numerals) to N spoken TTS words.
"""
import json, os, subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VO = os.path.join(ROOT, "build", "vo")

ORDER = ["h1", "h2", "f1", "a1", "a2", "a3", "m1", "c1", "c2"]
GAP_BEFORE = {"h1": 0.5, "h2": 0.45, "f1": 0.7, "a1": 0.65, "a2": 0.5, "a3": 0.5, "m1": 2.0, "c1": 0.8, "c2": 0.9}
CHUNKS = {
    "h1": [("Korang tahu tak...", 3), ("Malaysia pernah menjadi lokasi satu tragedi", 6),
           ("melibatkan sebuah pesawat jumbo jet", 5), ("Boeing 747", 4),
           ("yang terhempas ketika menghampiri", 4), ("Lapangan Terbang Subang?", 3)],
    "h2": [("Kejadian ini berlaku", 3), ("pada tahun 1989.", 7)],
    "f1": [("Pada 19 Februari 1989,", 9), ("Flying Tiger Line Flight 66,", 5), ("sebuah Boeing 747-200F,", 8),
           ("dengan pendaftaran N807FT,", 8), ("sedang dalam perjalanan dari Singapura", 5),
           ("menuju ke Kuala Lumpur,", 4), ("sebelum meneruskan penerbangan ke Hong Kong.", 6)],
    "a1": [("Ketika menghampiri Subang", 3), ("untuk mendarat di Runway 33,", 6),
           ("berlaku salah faham komunikasi", 4), ("antara juruterbang dan menara kawalan trafik udara.", 7)],
    "a2": [("Arahan untuk turun ke 2,400 kaki...", 9), ("telah disalahertikan sebagai 400 kaki.", 6)],
    "a3": [("Pesawat terus menurun...", 3), ("dan akhirnya melanggar kawasan berbukit", 5), ("berhampiran Puchong.", 2)],
    "m1": [("Tragedi pada awal pagi itu...", 5), ("mengorbankan kesemua empat individu", 4), ("di dalam pesawat tersebut.", 4)],
    "c1": [("Tragedi ini mengingatkan kita bahawa", 5), ("dalam dunia penerbangan,", 3),
           ("setiap arahan, dan setiap perkataan,", 5), ("membawa makna.", 2)],
    "c2": [],  # tagline is drawn on the end card
}

lines, t = [], 0.0
for k in ORDER:
    w = json.load(open(os.path.join(VO, f"{k}.json")))
    wav = os.path.join(VO, f"{k}.wav")
    subprocess.run(["ffmpeg", "-y", "-v", "error", "-i", os.path.join(VO, f"{k}.mp3"), "-ac", "1", "-ar", "48000", wav], check=True)
    t += GAP_BEFORE[k]
    off = t - w[0][0]
    words = [(a + off, b + off, x) for a, b, x in w]
    chunks, i = [], 0
    if CHUNKS[k]:
        assert sum(n for _, n in CHUNKS[k]) == len(words), (k, len(words))
    for txt, n in CHUNKS[k]:
        a, b = words[i][0], words[i + n - 1][1]
        nxt = words[i + n][0] if i + n < len(words) else b + 0.5
        chunks.append((a, min(nxt, b + 0.6), txt)); i += n
    lines.append(dict(key=k, start=words[0][0], end=words[-1][1], offset=off, wav=wav, words=words, chunks=chunks))
    t = words[-1][1]
json.dump(dict(lines=lines, end=t + 3.2), open(os.path.join(VO, "timeline.json"), "w"), ensure_ascii=False, indent=1)
print("end", round(t + 3.2, 2))
